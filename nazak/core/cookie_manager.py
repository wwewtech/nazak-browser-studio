"""
Cookie Manager: JSON and Netscape formats parsing, export, validation, and storage.
Handles #HttpOnly_ prefixes, float expiration dates, whitespace tolerances, and format conversions.
"""

import io
import json
import logging
import re
import zipfile
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

# Audit R3-round2: limits for the cookie ZIP (the archive arrives from the user
# through the GUI/CLI; without bounds a 100-kilobyte archive was unpacked into memory).
MAX_COOKIE_ZIP_ENTRIES = 200
MAX_COOKIE_ZIP_ENTRY_BYTES = 32 * 1024 * 1024
MAX_COOKIE_ZIP_TOTAL_BYTES = 64 * 1024 * 1024


def parse_netscape_cookies(text: str) -> list[dict[str, Any]]:
    """
    Parses standard Netscape HTTP Cookie file format into list of cookie dicts.
    Format: domain, flag, path, secure, expiration, name, value
    Also handles #HttpOnly_ domain prefix without skipping.
    """
    cookies = []
    # Do NOT strip() the whole text: that eats the trailing space/tab of the
    # last line, which is real VALUE content (round-trip fidelity).
    lines = text.splitlines()
    for raw_line in lines:
        # Trim CR only — NOT spaces/tabs: trailing whitespace is real VALUE
        # content (a trailing tab belongs to an empty value; a trailing space
        # is part of "abc "). splitlines() already removed the newline.
        line = raw_line.strip("\r")
        if not line.strip():
            continue

        http_only = False
        if line.startswith("#HttpOnly_"):
            http_only = True
            line = line[len("#HttpOnly_") :].strip(" \r")
        elif line.startswith("#"):
            continue

        # Split on tabs FIRST (the canonical format): that keeps inner spaces in
        # the VALUE intact. Only when a line has no tabs fall back to runs of
        # 2+ spaces — and there with a maxsplit so the trailing value keeps
        # its own spaces. The old unconditional `re.split(r"\t+|\s{2,}")`
        # truncated values like "mode=dark  lang=ru" and dropped empty values.
        if "\t" in line:
            parts = line.split("\t")
        else:
            parts = re.split(r"\s{2,}", line, maxsplit=6)
        if len(parts) >= 7:
            domain, include_subdomains, path, secure, expiration, name, value = parts[:7]
            try:
                exp_int = int(float(expiration))
            except (ValueError, TypeError):
                exp_int = 0

            cookies.append(
                {
                    "name": name.strip(),
                    # Preserve value whitespace fidelity: only a CR is trimmed.
                    # A full strip() truncated values with inner/trailing spaces.
                    "value": value.strip("\r"),
                    "domain": domain.strip(),
                    "path": path.strip() or "/",
                    "expires": exp_int,
                    "secure": secure.strip().lower() == "true",
                    "httpOnly": http_only,
                    "includeSubdomains": include_subdomains.strip().lower() == "true",
                }
            )
    return cookies


def cookies_to_netscape(cookies: list[dict[str, Any]]) -> str:
    """
    Converts list of cookie objects to Netscape format.
    """
    lines = ["# Netscape HTTP Cookie File", "# Generated by Nazak Browser Studio", ""]
    for c in cookies:
        if not isinstance(c, dict):
            continue
        domain = str(c.get("domain", "")).strip()
        if "includeSubdomains" in c:
            include_subdomains = "TRUE" if c.get("includeSubdomains") else "FALSE"
        else:
            include_subdomains = "TRUE" if domain.startswith(".") else "FALSE"
        path = str(c.get("path", "/")).strip() or "/"
        secure = "TRUE" if c.get("secure", False) else "FALSE"

        raw_exp = c.get("expires") or c.get("expirationDate") or 0
        try:
            expires = str(int(float(raw_exp)))
        except (ValueError, TypeError):
            expires = "0"

        name = str(c.get("name", "")).strip()
        # Preserve the value byte-for-byte: a strip() here broke the round-trip
        # fidelity (trailing/leading spaces in values never survived export).
        value = str(c.get("value", ""))

        prefix = "#HttpOnly_" if c.get("httpOnly", False) else ""
        lines.append(f"{prefix}{domain}\t{include_subdomains}\t{path}\t{secure}\t{expires}\t{name}\t{value}")
    return "\n".join(lines)


def parse_any_cookies(raw_text: str) -> list[dict[str, Any]]:
    """
    Parses JSON array or Netscape formatted cookies automatically with field normalization.
    """
    if not raw_text:
        return []
    text = raw_text.strip()
    if text.startswith("[") or text.startswith("{"):
        try:
            data = json.loads(text)
            if isinstance(data, dict):
                data = [data]
            if isinstance(data, list):
                sanitized = []
                for item in data:
                    if isinstance(item, dict) and item.get("name"):
                        sanitized.append(
                            {
                                "name": str(item.get("name", "")),
                                "value": str(item.get("value", "")),
                                "domain": str(item.get("domain", "")),
                                "path": str(item.get("path", "/")),
                                "expires": int(float(item.get("expirationDate") or item.get("expires") or 0)),
                                "secure": bool(item.get("secure", False)),
                                "httpOnly": bool(item.get("httpOnly", False)),
                            }
                        )
                if sanitized:
                    return sanitized
        except Exception:
            # Fall through to the Netscape parser, but leave a trace: a JSON
            # cookie payload that fails to parse silently looked like "0 cookies
            # imported" with no hint why.
            logger.warning("cookie payload looked like JSON but failed to parse; trying Netscape", exc_info=True)
    return parse_netscape_cookies(text)


def parse_bulk_cookie_input(raw_input: str) -> dict[str, list[dict[str, Any]]]:
    """
    Parses bulk multi-profile cookie data in various popular formats:
    1. Delimited blocks:
       === Profile 01 ===
       [{"name": "SID", ...}]
       === Profile 02 ===
       # Netscape HTTP Cookie File
       ...
    2. JSON dictionary mapping profile identifier to cookie list/string:
       {"prof_01": [...], "prof_02": [...]}
    3. Single cookie list/string -> returned as {"default": [...]}
    """
    if not raw_input or not raw_input.strip():
        return {}

    text = raw_input.strip()

    # Case 1: Check if input is a JSON dictionary mapping profile_name -> cookies
    if text.startswith("{"):
        try:
            data = json.loads(text)
            if isinstance(data, dict):
                # Check if it's a map of {profile_id: cookies}
                result = {}
                is_map = False
                for key, val in data.items():
                    if isinstance(val, (list, dict, str)):
                        if isinstance(val, str):
                            parsed = parse_any_cookies(val)
                        elif isinstance(val, dict):
                            parsed = parse_any_cookies(json.dumps([val]))
                        else:
                            parsed = parse_any_cookies(json.dumps(val))
                        if parsed:
                            result[str(key).strip()] = parsed
                            is_map = True
                if is_map and result:
                    return result
        except Exception:
            pass

    # Case 2: Delimited sections with === Name === or --- Name --- or ### Name or [Profile Name]
    delimiter_pattern = re.compile(
        r"^\s*(?:(?:={2,}|-{2,}|#{2,}|\/{2,})\s*([^\r\n=\-\#\/]+?)\s*(?:={2,}|-{2,}|#{2,}|\/{2,})?|\[([a-zA-Z0-9_\- .]+)\])\s*$",
        re.MULTILINE,
    )
    matches = list(delimiter_pattern.finditer(text))

    if matches:
        sections: dict[str, list[dict[str, Any]]] = {}
        for i, match in enumerate(matches):
            prof_name = (match.group(1) or match.group(2) or "").strip()
            if not prof_name:
                continue
            start_pos = match.end()
            end_pos = matches[i + 1].start() if i + 1 < len(matches) else len(text)
            chunk = text[start_pos:end_pos].strip()
            if chunk:
                parsed = parse_any_cookies(chunk)
                if parsed:
                    sections[prof_name] = parsed
        if sections:
            return sections

    # Case 3: Fallback single profile cookies
    single = parse_any_cookies(text)
    if single:
        return {"default": single}
    return {}


def parse_cookie_files_from_dir(dir_path: Path) -> dict[str, list[dict[str, Any]]]:
    """
    Scans a directory for .json and .txt cookie files and parses them into a profile-indexed map.
    File name (without extension) is treated as the profile identifier (ID or Name).
    """
    results: dict[str, list[dict[str, Any]]] = {}
    if not dir_path.exists() or not dir_path.is_dir():
        return results

    for file_path in dir_path.glob("*"):
        if file_path.is_file() and file_path.suffix.lower() in (".json", ".txt"):
            try:
                content = file_path.read_text(encoding="utf-8", errors="ignore")
                cookies = parse_any_cookies(content)
                if cookies:
                    results[file_path.stem] = cookies
            except Exception:
                continue
    return results


def parse_cookie_files_from_zip(zip_source: Any) -> dict[str, list[dict[str, Any]]]:
    """
    Extracts and parses all .json / .txt cookie files from a zip archive (Path, bytes, or file-like object).
    """
    results: dict[str, list[dict[str, Any]]] = {}
    try:
        if isinstance(zip_source, (str, Path)):
            zf = zipfile.ZipFile(zip_source, "r")
        elif isinstance(zip_source, bytes):
            zf = zipfile.ZipFile(io.BytesIO(zip_source), "r")
        else:
            zf = zipfile.ZipFile(zip_source, "r")

        with zf:
            infos = zf.infolist()
            # Audit R3-round2: cookie archives are also read into memory in full,
            # so we cap the entry count and the total size.
            if len(infos) > MAX_COOKIE_ZIP_ENTRIES:
                return results
            total_declared = sum(max(0, info.file_size) for info in infos)
            if total_declared > MAX_COOKIE_ZIP_TOTAL_BYTES:
                return results
            consumed = 0
            for info in infos:
                name = info.filename
                if name.endswith("/") or name.startswith("__MACOSX"):
                    continue
                p = Path(name)
                if p.suffix.lower() in (".json", ".txt"):
                    try:
                        if info.file_size > MAX_COOKIE_ZIP_ENTRY_BYTES:
                            continue
                        blob = zf.read(name)
                        consumed += len(blob)
                        if consumed > MAX_COOKIE_ZIP_TOTAL_BYTES:
                            return results
                        content = blob.decode("utf-8", errors="ignore")
                        cookies = parse_any_cookies(content)
                        if cookies:
                            results[p.stem] = cookies
                    except Exception:
                        continue
    except Exception:
        pass
    return results


def create_cookies_zip_archive(cookie_map: dict[str, list[dict[str, Any]]], format_type: str = "json") -> bytes:
    """
    Creates a zip archive containing individual cookie files for each profile.
    format_type: 'json' or 'netscape'
    """
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for prof_id, cookies in cookie_map.items():
            safe_name = re.sub(r'[\/:*?"<>|]', "_", prof_id)
            if format_type.lower() == "netscape":
                content = cookies_to_netscape(cookies)
                zf.writestr(f"{safe_name}.txt", content)
            else:
                content = json.dumps(cookies, indent=2, ensure_ascii=False)
                zf.writestr(f"{safe_name}.json", content)
    return buf.getvalue()
